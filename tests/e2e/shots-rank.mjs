// ふりかえり(関連がありそうな要因)の見た目確認（架空データのみ）: node tests/e2e/shots-rank.mjs <出力ディレクトリ> <架空バックアップJSON>
import { chromium } from 'playwright-core';
import { spawn } from 'node:child_process';
const [out = '.', json] = process.argv.slice(2);
const srv = spawn('npx', ['vite', 'preview', '--port', '4179', '--strictPort'], { stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 2500));
const b = await chromium.launch({ executablePath: process.env.CHROMIUM, args: ['--no-sandbox'] });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, locale: 'ja-JP' });
const p = await ctx.newPage();
p.on('dialog', (d) => d.accept());
await p.goto('http://localhost:4179/buhilog/');
await p.getByRole('button', { name: 'はじめる' }).click();
await p.getByRole('button', { name: '後で登録する' }).click();
await p.getByRole('button', { name: '設定' }).click();
await p.locator('input[type=file]').setInputFiles(json);
await p.getByRole('button', { name: 'この内容で置き換える' }).click();
await p.getByRole('tablist', { name: '記録の種類' }).waitFor();
await p.getByRole('button', { name: 'ふりかえり' }).click();
await p.getByRole('radio', { name: '全期間' }).click();
await p.getByText('関連がありそうな要因').evaluate((el) => el.scrollIntoView({ block: 'start' }));
await p.evaluate(() => window.scrollBy(0, -20));
await p.screenshot({ path: `${out}/14-rank.png` });
await p.locator('.cand').first().click();
await p.screenshot({ path: `${out}/15-rank-open.png` });
await b.close(); srv.kill();
