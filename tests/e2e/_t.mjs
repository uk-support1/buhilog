import { chromium } from 'playwright-core';
import { spawn } from 'node:child_process';
const [out] = process.argv.slice(2);
const srv = spawn('npx', ['vite', 'preview', '--port', '4191', '--strictPort'], { stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 2500));
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox'] });
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, locale: 'ja-JP' });
const p = await ctx.newPage();
await p.goto('http://localhost:4191/buhilog/');
await p.getByRole('button', { name: 'はじめる' }).click();
await p.getByRole('button', { name: '後で登録する' }).click();
await p.getByRole('button', { name: /^ToDo/ }).click();
await p.getByLabel('いつかに追加').fill('歯医者の予約をする'); await p.getByLabel('いつかに追加').press('Enter'); await p.waitForTimeout(200);
await p.getByLabel('歯医者の予約をするを移す').selectOption('calendar');
await p.getByLabel('予定の日付').fill('2026-12-02');
await p.getByRole('checkbox', { name: /終日/ }).uncheck();
await p.waitForTimeout(200);
await p.screenshot({ path: `${out}/35-tocal.png` });
await p.getByRole('button', { name: '予定にする' }).click();
await p.waitForTimeout(300);
await p.getByRole('button', { name: '予定', exact: true }).click();
await p.getByRole('button', { name: /12月2日/ }).first().click();
await p.waitForTimeout(300);
await p.screenshot({ path: `${out}/36-cal-after.png` });
await b.close(); srv.kill();
